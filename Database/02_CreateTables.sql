-- 1. EF Core Migrations History (Ensures EF Core and manual scripts stay 100% in sync)
CREATE TABLE IF NOT EXISTS "__EFMigrationsHistory" (
    "MigrationId" character varying(150) NOT NULL,
    "ProductVersion" character varying(32) NOT NULL,
    CONSTRAINT "PK___EFMigrationsHistory" PRIMARY KEY ("MigrationId")
);

-- 2. Admin Users
CREATE TABLE IF NOT EXISTS admin_users (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Username" character varying(100) NOT NULL,
    "Email" character varying(150) NOT NULL,
    "PasswordHash" character varying(255) NOT NULL,
    "FullName" character varying(150) NOT NULL,
    "Role" integer NOT NULL DEFAULT 2, -- 1=SuperAdmin, 2=Admin, 3=Manager
    "IsActive" boolean NOT NULL DEFAULT TRUE,
    "LastLoginAt" timestamp with time zone,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_admin_users" PRIMARY KEY ("Id")
);

-- 3. Customers
CREATE TABLE IF NOT EXISTS customers (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "FullName" character varying(150) NOT NULL,
    "Email" character varying(150) NOT NULL,
    "PhoneNumber" character varying(50) NOT NULL,
    "CompanyName" character varying(150),
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_customers" PRIMARY KEY ("Id")
);

-- 4. Service Categories
CREATE TABLE IF NOT EXISTS service_categories (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Name" character varying(150) NOT NULL,
    "Slug" character varying(150) NOT NULL,
    "Description" character varying(1000) NOT NULL,
    "IconName" character varying(50),
    "DisplayOrder" integer NOT NULL DEFAULT 0,
    "IsActive" boolean NOT NULL DEFAULT TRUE,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_service_categories" PRIMARY KEY ("Id")
);

-- 5. Services
CREATE TABLE IF NOT EXISTS services (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ServiceCategoryId" integer NOT NULL,
    "Title" character varying(200) NOT NULL,
    "Slug" character varying(200) NOT NULL,
    "ShortDescription" character varying(500) NOT NULL,
    "FullDescription" text NOT NULL,
    "FeaturesJson" text NOT NULL DEFAULT '[]',
    "TechnologiesJson" text NOT NULL DEFAULT '[]',
    "BenefitsJson" text NOT NULL DEFAULT '[]',
    "IconName" character varying(50),
    "DisplayOrder" integer NOT NULL DEFAULT 0,
    "IsActive" boolean NOT NULL DEFAULT TRUE,
    "IsFeatured" boolean NOT NULL DEFAULT FALSE,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_services" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_services_service_categories" FOREIGN KEY ("ServiceCategoryId")
        REFERENCES service_categories ("Id") ON DELETE RESTRICT
);

-- 6. Enquiries
CREATE TABLE IF NOT EXISTS enquiries (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ReferenceNumber" character varying(50) NOT NULL,
    "CustomerId" integer NOT NULL,
    "ServiceCategoryId" integer,
    "RequiredTechnology" character varying(150) NOT NULL,
    "ProjectTitle" character varying(250) NOT NULL,
    "ProjectDescription" text NOT NULL,
    "EstimatedBudget" character varying(100) NOT NULL,
    "ExpectedCompletionDate" timestamp with time zone,
    "AdditionalRequirements" text,
    "Status" integer NOT NULL DEFAULT 1, -- 1=New, 2=Reviewed, 3=Quoted, 4=FollowUp, 5=Converted, 6=Closed, 7=Spam
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_enquiries" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_enquiries_customers" FOREIGN KEY ("CustomerId")
        REFERENCES customers ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_enquiries_service_categories" FOREIGN KEY ("ServiceCategoryId")
        REFERENCES service_categories ("Id") ON DELETE SET NULL
);

-- 7. Enquiry Attachments
CREATE TABLE IF NOT EXISTS enquiry_attachments (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "EnquiryId" integer NOT NULL,
    "OriginalFileName" character varying(255) NOT NULL,
    "StoredFileName" character varying(255) NOT NULL,
    "ContentType" character varying(100) NOT NULL,
    "FileSizeBytes" bigint NOT NULL,
    "StoragePath" character varying(500) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_enquiry_attachments" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_enquiry_attachments_enquiries" FOREIGN KEY ("EnquiryId")
        REFERENCES enquiries ("Id") ON DELETE CASCADE
);

-- 8. Enquiry Notes
CREATE TABLE IF NOT EXISTS enquiry_notes (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "EnquiryId" integer NOT NULL,
    "AdminUserId" integer,
    "NoteContent" text NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_enquiry_notes" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_enquiry_notes_enquiries" FOREIGN KEY ("EnquiryId")
        REFERENCES enquiries ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_enquiry_notes_admin_users" FOREIGN KEY ("AdminUserId")
        REFERENCES admin_users ("Id") ON DELETE SET NULL
);

-- 9. Quotations
CREATE TABLE IF NOT EXISTS quotations (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "QuotationNumber" character varying(50) NOT NULL,
    "EnquiryId" integer NOT NULL,
    "CustomerId" integer NOT NULL,
    "ServiceDescription" text NOT NULL,
    "Deliverables" text NOT NULL,
    "DevelopmentCost" numeric(18,2) NOT NULL DEFAULT 0.00,
    "AdditionalCost" numeric(18,2) NOT NULL DEFAULT 0.00,
    "TaxRate" numeric(5,2) NOT NULL DEFAULT 0.00,
    "TaxAmount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "TotalAmount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "AdvancePaymentAmount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "RemainingPaymentAmount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "ExpectedDeliveryDate" timestamp with time zone NOT NULL,
    "ValidityDays" integer NOT NULL DEFAULT 15,
    "ValidUntil" timestamp with time zone NOT NULL,
    "TermsAndConditions" text NOT NULL,
    "Status" integer NOT NULL DEFAULT 1, -- 1=Draft, 2=Sent, 3=Viewed, 4=Accepted, 5=Rejected, 6=Expired, 7=Cancelled
    "SecureToken" character varying(100) NOT NULL,
    "SentAt" timestamp with time zone,
    "ViewedAt" timestamp with time zone,
    "RespondedAt" timestamp with time zone,
    "ResponseRemarks" text,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_quotations" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_quotations_enquiries" FOREIGN KEY ("EnquiryId")
        REFERENCES enquiries ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_quotations_customers" FOREIGN KEY ("CustomerId")
        REFERENCES customers ("Id") ON DELETE RESTRICT
);

-- 10. Quotation Items
CREATE TABLE IF NOT EXISTS quotation_items (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "QuotationId" integer NOT NULL,
    "Title" character varying(200) NOT NULL,
    "Description" text NOT NULL,
    "Quantity" integer NOT NULL DEFAULT 1,
    "UnitPrice" numeric(18,2) NOT NULL DEFAULT 0.00,
    "TotalPrice" numeric(18,2) NOT NULL DEFAULT 0.00,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_quotation_items" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_quotation_items_quotations" FOREIGN KEY ("QuotationId")
        REFERENCES quotations ("Id") ON DELETE CASCADE
);

-- 11. Quotation Status History
CREATE TABLE IF NOT EXISTS quotation_status_histories (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "QuotationId" integer NOT NULL,
    "PreviousStatus" integer,
    "NewStatus" integer NOT NULL,
    "ChangedBy" character varying(100) NOT NULL DEFAULT 'System',
    "Remarks" text,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_quotation_status_histories" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_quotation_status_histories_quotations" FOREIGN KEY ("QuotationId")
        REFERENCES quotations ("Id") ON DELETE CASCADE
);

-- 12. Projects
CREATE TABLE IF NOT EXISTS projects (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ProjectNumber" character varying(50) NOT NULL,
    "QuotationId" integer,
    "CustomerId" integer NOT NULL,
    "ProjectTitle" character varying(250) NOT NULL,
    "Description" text NOT NULL,
    "StartDate" timestamp with time zone NOT NULL,
    "ExpectedCompletionDate" timestamp with time zone NOT NULL,
    "ActualCompletionDate" timestamp with time zone,
    "AgreedAmount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "Status" integer NOT NULL DEFAULT 1, -- 1=NotStarted, 2=InProgress, 3=OnHold, 4=Completed, 5=Cancelled
    "ProgressPercentage" integer NOT NULL DEFAULT 0,
    "AssignedDeveloper" character varying(150),
    "InternalNotes" text,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_projects" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_projects_customers" FOREIGN KEY ("CustomerId")
        REFERENCES customers ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_projects_quotations" FOREIGN KEY ("QuotationId")
        REFERENCES quotations ("Id") ON DELETE SET NULL
);

-- 13. Project Milestones
CREATE TABLE IF NOT EXISTS project_milestones (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ProjectId" integer NOT NULL,
    "Title" character varying(200) NOT NULL,
    "Description" text NOT NULL,
    "DueDate" timestamp with time zone NOT NULL,
    "IsCompleted" boolean NOT NULL DEFAULT FALSE,
    "CompletedAt" timestamp with time zone,
    "Amount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_project_milestones" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_project_milestones_projects" FOREIGN KEY ("ProjectId")
        REFERENCES projects ("Id") ON DELETE CASCADE
);

-- 14. Payments
CREATE TABLE IF NOT EXISTS payments (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ProjectId" integer NOT NULL,
    "CustomerId" integer NOT NULL,
    "PaymentType" integer NOT NULL DEFAULT 1, -- 1=Advance, 2=Milestone, 3=Final, 4=Additional
    "PaymentDate" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "Amount" numeric(18,2) NOT NULL DEFAULT 0.00,
    "PaymentMethod" character varying(100) NOT NULL,
    "TransactionReference" character varying(150),
    "Status" integer NOT NULL DEFAULT 2, -- 1=Pending, 2=Received, 3=Refunded
    "Notes" text,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone,
    "IsDeleted" boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT "PK_payments" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_payments_projects" FOREIGN KEY ("ProjectId")
        REFERENCES projects ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_payments_customers" FOREIGN KEY ("CustomerId")
        REFERENCES customers ("Id") ON DELETE RESTRICT
);

